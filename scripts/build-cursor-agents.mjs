// Writes <kit>/cursor-agents/*.md from <kit>/agents/*.md with Cursor model ids from
// scripts/model-tiers.json. Claude Code keeps reading agents/; Cursor manifests point at cursor-agents/.
//   node scripts/build-cursor-agents.mjs          regenerate
//   node scripts/build-cursor-agents.mjs --check  exit 1 when cursor-agents/ is out of date
import { existsSync, mkdirSync, readdirSync, readFileSync, unlinkSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const check = process.argv.includes("--check");
const { cursor, kits } = JSON.parse(readFileSync(join(root, "scripts", "model-tiers.json"), "utf8"));
const READ_ONLY_TOOLS = new Set(["Read", "Grep", "Glob"]);

function transform(source, file) {
  const lines = source.split("\n");
  const end = lines.indexOf("---", 1);
  if (lines[0] !== "---" || end === -1) throw new Error(`${file}: no frontmatter`);
  const front = lines.slice(1, end);
  const get = (key) => front.find((l) => l.startsWith(`${key}:`))?.slice(key.length + 1).trim();

  const model = get("model");
  const effort = get("effort");
  const tier = model === "sonnet" && ["high", "xhigh"].includes(effort) ? "sonnet+effort" : model;
  const id = cursor[tier];
  if (!id) throw new Error(`${file}: no Cursor mapping for model "${model}"`);

  const tools = get("tools")
    ?.replace(/^\[|\]$/g, "")
    .split(",")
    .map((t) => t.trim())
    .filter(Boolean);
  const readonly = tools?.length && tools.every((t) => READ_ONLY_TOOLS.has(t));

  const out = ["---", `# Generated by scripts/build-cursor-agents.mjs from agents/${file}. Do not edit.`];
  for (const line of front) {
    if (line.startsWith("effort:") || line.startsWith("readonly:")) continue;
    if (line.startsWith("model:")) {
      out.push(`model: ${id}`);
      if (readonly) out.push("readonly: true");
      continue;
    }
    out.push(line);
  }
  return [...out, ...lines.slice(end)].join("\n");
}

let stale = 0;
for (const kit of kits) {
  const src = join(root, kit, "agents");
  const dest = join(root, kit, "cursor-agents");
  const files = readdirSync(src).filter((f) => f.endsWith(".md"));
  if (!check) mkdirSync(dest, { recursive: true });

  for (const file of files) {
    const want = transform(readFileSync(join(src, file), "utf8"), file);
    const target = join(dest, file);
    if (existsSync(target) && readFileSync(target, "utf8") === want) continue;
    if (check) {
      console.error(`STALE: ${kit}/cursor-agents/${file}`);
      stale++;
    } else {
      writeFileSync(target, want);
      console.log(`wrote ${kit}/cursor-agents/${file}`);
    }
  }

  const extras = existsSync(dest) ? readdirSync(dest).filter((f) => !files.includes(f)) : [];
  for (const extra of extras) {
    if (check) {
      console.error(`EXTRA: ${kit}/cursor-agents/${extra}`);
      stale++;
    } else {
      unlinkSync(join(dest, extra));
      console.log(`removed ${kit}/cursor-agents/${extra}`);
    }
  }
}

if (stale) {
  console.error(`FAIL: ${stale} Cursor agent file(s) out of date. Run: npm run build:cursor-agents`);
  process.exit(1);
}
console.log(check ? "OK: cursor-agents/ up to date" : "Done.");
