#!/usr/bin/env node
// Render human-readable tables and Mermaid diagrams (state machines, screen navigation, API
// sequences, user flows) from the spec YAML into spec.views.md (next to spec.md).
// These views replace hand-written body tables and diagrams: they are regenerated, never edited.
// Usage: node render-spec-views.mjs <spec.md> [--out <file>]

import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { endpointsOf, flag, loadYaml, readSpec } from './lib-spec.mjs'

const args = process.argv.slice(2)
const specPath = args.find((a) => !a.startsWith('--') && a !== flag(args, 'out'))
if (!specPath) {
  console.error('usage: node render-spec-views.mjs <spec.md> [--out <file>]')
  process.exit(2)
}
const outArg = flag(args, 'out')
const outPath = outArg && outArg !== true ? String(outArg) : join(dirname(specPath), 'spec.views.md')

const { parse } = await loadYaml()
const { fm } = readSpec(specPath, parse)
const list = (v) => (Array.isArray(v) ? v : [])
const cell = (v) => String(Array.isArray(v) ? v.join(', ') : v ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ')
const table = (head, rows) => rows.length
  ? [`| ${head.join(' | ')} |`, `|${head.map(() => '---').join('|')}|`, ...rows.map((r) => `| ${r.map(cell).join(' | ')} |`)].join('\n')
  : '_None._'

const out = []
const title = fm.metadata?.title ?? fm.metadata?.slug ?? 'Spec'
out.push(`# ${title} — generated views`, '')
out.push(`> Generated by \`render-spec-views.mjs\` from \`${specPath}\` (spec-version ${fm['spec-version']}, status ${fm.status}). Do not edit — change the spec and re-render.`, '')

// Delivery plan
const slices = list(fm['delivery-plan']?.slices)
out.push('## Delivery plan', '')
if (fm['delivery-plan']?.strategy) out.push(fm['delivery-plan'].strategy, '')
out.push(table(
  ['#', 'Slice', 'Tracks', 'Depends on', 'Stories', 'Screens', 'Endpoints', 'Done when'],
  slices.map((s, i) => [i + 1, `${s.id} ${s.title}`, s.tracks, s['depends-on'], s['story-refs'], s['screen-refs'], s['api-refs'], s['done-when']]),
), '')
for (const s of slices) {
  out.push(`### ${s.id} — ${s.title}`, '', `**Goal:** ${s.goal ?? ''}`, '')
  list(s.steps).forEach((step, i) => out.push(`${i + 1}. **${step.track}** — ${step.do}${list(step.refs).length ? ` _(${list(step.refs).join(', ')})_` : ''}`))
  out.push('')
}

// Requirement coverage
const reqs = list(fm.requirements)
const uncovered = reqs.filter((r) => (r.scope ?? 'in') === 'in' && !list(r['covered-by']).length)
out.push('## Requirement coverage', '', `${reqs.length} requirements · ${uncovered.length} in scope without coverage`, '')
out.push(table(
  ['Id', 'Priority', 'Kind', 'Source', 'Scope', 'Covered by', 'Text'],
  reqs.map((r) => [r.id, r.priority, r.kind, r['source-ref'] ?? r.source, r.scope ?? 'in', list(r['covered-by']).length ? r['covered-by'] : '✗', r.text]),
), '')

// Story → AC map
const acs = list(fm['acceptance-criteria'])
out.push('## Stories and acceptance criteria', '')
out.push(table(
  ['Story', 'Priority', 'As', 'I want', 'Happy', 'Error / edge / permission'],
  list(fm['user-stories']).map((s) => {
    const own = acs.filter((a) => a['story-ref'] === s.id)
    return [s.id, s.priority, s.as, s['i-want'], own.filter((a) => a.kind === 'happy').map((a) => a.id), own.filter((a) => a.kind !== 'happy').map((a) => `${a.id}${a.kind ? ` (${a.kind})` : ''}`)]
  }),
), '')

// Permissions matrix
const roles = list(fm.roles).map((r) => r.name)
out.push('## Permissions', '')
out.push(table(
  ['Action', ...roles],
  list(fm.permissions).map((p) => [
    `${p.id} ${p.action}`,
    ...roles.map((r) => (list(p.allow).includes(r) ? '✓' : p.conditional?.[r] ? `if ${p.conditional[r]}` : '—')),
  ]),
), '')

// Business rules
out.push('## Business rules', '')
out.push(table(
  ['Id', 'Rule', 'Params', 'Applies to', 'On violation', 'Tested by'],
  list(fm['business-rules']).map((b) => [b.id, b.rule, JSON.stringify(b.params ?? {}), b['applies-to'], b['on-violation'], b['ac-refs']]),
), '')

// State machines (deterministic Mermaid)
out.push('## State machines', '')
for (const m of list(fm['state-machines'])) {
  out.push(`### ${m.id} — ${m.entity}.${m.field ?? 'status'}`, '', '```mermaid', 'stateDiagram-v2', `  [*] --> ${m.initial}`)
  for (const t of list(m.transitions)) {
    const froms = t.from === '*' ? list(m.states).filter((s) => s !== t.to) : [t.from]
    const label = `${t.trigger}${t.after ? ` (after ${t.after})` : ''}`.replace(/[:;]/g, ',')
    for (const from of froms) out.push(`  ${from} --> ${t.to}: ${label}`)
  }
  out.push('```', '')
  out.push(table(
    ['From', 'To', 'Trigger', 'Actor', 'After', 'Guard', 'Effects', 'ACs'],
    list(m.transitions).map((t) => [t.from, t.to, t.trigger, t.actor, t.after, t.guard, t.effects, t['ac-refs']]),
  ), '')
}

// Flow diagrams (deterministic Mermaid): screen navigation, write-endpoint sequences, must-story flows
const node = (id) => String(id).replace(/[^A-Za-z0-9_]/g, '_')
const lbl = (s) => `"${String(s ?? '').replace(/"/g, '#quot;').replace(/\s+/g, ' ').trim()}"`
const msg = (s) => String(s ?? '').replace(/[;#]/g, ',').replace(/\s+/g, ' ').trim()
const screens = list(fm['ui-surface']?.screens)
const navs = list(fm['ui-surface']?.interactions).filter((i) => i['target-screen'])
out.push('## Screen navigation', '')
if (navs.length) {
  out.push('```mermaid', 'flowchart LR')
  const byRole = new Map()
  for (const s of screens) {
    const role = list(s.roles)[0] ?? 'Any role'
    byRole.set(role, [...(byRole.get(role) ?? []), s])
  }
  for (const [role, group] of byRole) {
    out.push(`  subgraph ${node(`role_${role}`)}[${lbl(role)}]`)
    for (const s of group) out.push(`    ${node(s.id)}[${lbl(`${s.id} ${s.title ?? ''}`)}]`)
    out.push('  end')
  }
  for (const i of navs) out.push(`  ${node(i['screen-ref'])} -- ${lbl(`${i.id} ${i.trigger ?? ''}`)} --> ${node(i['target-screen'])}`)
  out.push('```', '')
} else out.push('_No navigating interactions._', '')

const stories = list(fm['user-stories'])
const rules = list(fm['business-rules'])
const machines = list(fm['state-machines'])
const ntfById = new Map(list(fm.notifications).map((n) => [n.id, n]))
const writes = endpointsOf(fm).filter((e) => ['POST', 'PUT', 'PATCH', 'DELETE'].includes(String(e.method).toUpperCase()))
out.push('## API sequences', '')
if (!writes.length) out.push('_No write endpoints._', '')
for (const e of writes) {
  const story = stories.find((s) => list(e['story-refs']).includes(s.id))
  const actor = msg(list(e.roles)[0] ?? 'User')
  out.push(`### ${e.id} — ${e.method} ${e.path}`, '', '```mermaid', 'sequenceDiagram', `  actor User as ${actor}`, '  participant Frontend', '  participant API')
  out.push(`  User->>Frontend: ${msg(story?.['i-want'] ?? e.description)}`, `  Frontend->>API: ${e.method} ${msg(e.path)}`)
  const errors = list(e.response?.errors)
  const checks = rules.filter((b) => list(b['applies-to']).includes(e.id))
  if (errors.length) {
    out.push(`  alt ${msg(errors[0].when ?? `${errors[0].status}`)}`, `    API-->>Frontend: ${errors[0].status} ${msg(errors[0].code ?? '')}`, `    Frontend-->>User: ${msg(errors[0].message ?? 'error')}`)
    for (const x of errors.slice(1)) out.push(`  else ${msg(x.when ?? `${x.status}`)}`, `    API-->>Frontend: ${x.status} ${msg(x.code ?? '')}`, `    Frontend-->>User: ${msg(x.message ?? 'error')}`)
    out.push('  else success')
  }
  const pad = errors.length ? '    ' : '  '
  for (const b of checks) out.push(`${pad}Note over API: ${b.id} ${msg(b.name ?? b.rule)}`)
  out.push(`${pad}API-->>Frontend: ${e.response?.success?.status ?? 200} ${msg(e.response?.success?.schema ?? '')}`, `${pad}Frontend-->>User: ${msg(e.description)}`)
  const effects = machines.flatMap((m) => list(m.transitions)).filter((t) => t['api-ref'] === e.id).flatMap((t) => list(t.effects))
  for (const id of new Set(effects)) {
    const n = ntfById.get(id)
    if (n) out.push(`${pad}Note over API: ${id} notify ${msg(list(n.recipients).join(', '))} - ${msg(n.event)}`)
  }
  if (errors.length) out.push('  end')
  out.push('```', '')
}

out.push('## User flows', '')
const mustStories = stories.filter((s) => s.priority === 'must')
if (!mustStories.length) out.push('_No must stories._', '')
for (const s of mustStories) {
  const own = acs.filter((a) => a['story-ref'] === s.id)
  out.push(`### ${s.id} — ${s.title ?? s['i-want'] ?? ''}`, '', '```mermaid', 'flowchart TD', `  ${node(s.id)}[${lbl(`${s.as}: ${s['i-want'] ?? ''}`)}]`)
  for (const a of own) {
    out.push(`  ${node(s.id)} --> ${node(a.id)}{${lbl(`${a.id} ${a.kind ?? ''}: ${a.when ?? ''}`)}}`)
    out.push(`  ${node(a.id)} --> ${node(`${a.id}_then`)}[${lbl(a.then)}]`)
  }
  out.push('```', '')
}

// Notifications
out.push('## Notifications', '')
out.push(table(
  ['Id', 'Event', 'Recipients', 'Channels', 'Mandatory', 'Timing', 'Copy'],
  list(fm.notifications).map((n) => [n.id, n.event, n.recipients, n.channels, n.mandatory ? 'yes' : 'no', n.timing, n.copy]),
), '')

// API
out.push('## Endpoints', '')
out.push(table(
  ['Id', 'Method', 'Path', 'Auth', 'Roles', 'Stories', 'Errors', 'Purpose'],
  endpointsOf(fm).map((e) => [
    e.id, e.method, e.path, e['auth-required'] === false ? 'public' : 'session', e.roles, e['story-refs'],
    list(e.response?.errors).map((x) => `${x.status}${x.code ? ` ${x.code}` : ''}`), e.description,
  ]),
), '')

// Screens
out.push('## Screens', '')
out.push(table(
  ['Id', 'Title', 'Route', 'Page type', 'Primary entity', 'Roles', 'Stories', 'Endpoints', 'Components'],
  list(fm['ui-surface']?.screens).map((s) => [s.id, s.title, s.route, s['page-type'], s['primary-entity'], s.roles, s['story-refs'], s['api-refs'], s.components]),
), '')

// Data model
out.push('## Data model', '')
for (const e of list(fm.entities)) {
  out.push(`### ${e.name}`, '', e.description ?? '', '')
  if (e.retention) out.push(`**Retention:** ${e.retention}`, '')
  out.push(table(
    ['Field', 'Type', 'Required', 'Values', 'Description'],
    list(e.fields).map((f) => [f.name, `${f.type}${f.derived ? ' (derived)' : ''}`, f.required ? '✓' : '', f.values, f.description]),
  ), '')
  if (list(e.relationships).length) {
    out.push(table(['Related', 'Type', 'Via', 'Meaning'], list(e.relationships).map((r) => [r.entity, r.type, r.via, r.description])), '')
  }
}

// Open items
out.push('## Open items', '')
out.push(table(
  ['Id', 'Kind', 'Text', 'Blocking / confirm', 'Affects'],
  [
    ...list(fm['open-questions']).filter((q) => q.status !== 'resolved').map((q) => [q.id, 'question', q.question, q.blocking ? 'blocking' : '', q.affects]),
    ...list(fm.assumptions).map((a) => [a.id, `assumption (${a.confidence})`, a.description, a['requires-confirmation'] ? 'confirm' : '', a.affects]),
  ],
), '')

writeFileSync(outPath, `${out.join('\n').replace(/\n{3,}/g, '\n\n')}\n`)
console.log(`OK: wrote ${outPath}`)
